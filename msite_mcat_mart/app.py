def prepare(df):
    for col in ("start_date", "end_date"):
        if col in df.columns:
            df[col] = pd.to_datetime(df[col], errors="coerce")
    if "week_mon_day" in df.columns:
        df["grain"] = df["week_mon_day"].map(GRAIN_LABELS).fillna(df["week_mon_day"].astype(str))
    for col, _, labels in CODE_DIMENSIONS:
        if col in df.columns:
            df[col] = df[col].map(labels).fillna(df[col].astype(str))
    return df


@st.cache_data
def load_data(path):
    return prepare(pd.read_csv(path))


def top_filters(df):
    if "grain" in df.columns:
        grains = sorted(df["grain"].dropna().unique())
        selected_grain = st.radio("Grain", grains, index=0, horizontal=True)
        df = df[df["grain"] == selected_grain]

    cols = st.columns(len(CODE_DIMENSIONS))
    for col, (dim, label, _) in zip(cols, CODE_DIMENSIONS):
        if dim in df.columns:
            options = sorted(df[dim].dropna().unique())
            selected = col.multiselect(label, options, default=options)
            if selected:
                df = df[df[dim].isin(selected)]

    if "start_date" in df.columns and df["start_date"].notna().any():
        min_d, max_d = df["start_date"].min(), df["start_date"].max()
        date_range = st.date_input("Date range", value=(min_d, max_d), min_value=min_d, max_value=max_d)
        if isinstance(date_range, tuple) and len(date_range) == 2:
            start, end = pd.Timestamp(date_range[0]), pd.Timestamp(date_range[1])
            df = df[(df["start_date"] >= start) & (df["start_date"] <= end)]

    return df


def kpi_selector(label, kpi_dict, df, key):
    available = [c for c in kpi_dict if c in df.columns]
    return st.multiselect(
        label,
        available,
        format_func=lambda c: kpi_dict[c][0],
        key=key,
        help="\n".join(f"**{kpi_dict[c][0]}** — {kpi_dict[c][1]}" for c in available),
    )


def trend_chart(df, metrics, kpi_dict):
    if not metrics:
        return
    if "start_date" not in df.columns:
        st.info("No date column available for trend chart.")
        return

    trend = df.groupby("start_date")[metrics].sum().reset_index()
    melted = trend.melt(id_vars="start_date", var_name="metric", value_name="value")
    melted["metric"] = melted["metric"].map(lambda c: kpi_dict[c][0])
    fig = px.line(melted, x="start_date", y="value", color="metric", markers=True)
    st.plotly_chart(fig, use_container_width=True)

    cols = st.columns(len(metrics))
    for col, metric in zip(cols, metrics):
        col.metric(kpi_dict[metric][0], f"{df[metric].sum():,.0f}")


def main():
    st.set_page_config(page_title="Msite MCAT Mart", layout="wide")
    st.title("Msite MCAT Mart Dashboard")

    uploaded = st.sidebar.file_uploader("Upload mart export (CSV)", type="csv")
    if uploaded is not None:
        df = prepare(pd.read_csv(uploaded))
    else:
        try:
            df = load_data(DATA_PATH)
        except FileNotFoundError:
            st.warning(
                f"No data found at `{DATA_PATH}`. Upload a CSV export of msite_mcat_mart "
                "using the sidebar to populate the dashboard."
            )
            return

    filtered = top_filters(df)

    st.divider()
    col1, col2 = st.columns(2)
    with col1:
        conversion_selected = kpi_selector("Conversion KPIs", CONVERSION_KPIS, filtered, "conversion_kpis")
    with col2:
        click_selected = kpi_selector("Clicks & Users Data", CLICK_KPIS, filtered, "click_kpis")

    if conversion_selected:
        st.subheader("Conversion KPIs Trend")
        trend_chart(filtered, conversion_selected, CONVERSION_KPIS)

    if click_selected:
        st.subheader("Clicks & Users Data Trend")
        trend_chart(filtered, click_selected, CLICK_KPIS)

    if not conversion_selected and not click_selected:
        st.info("Select one or more KPIs above to see trendlines.")

    with st.expander("Raw Data"):
        st.dataframe(filtered, use_container_width=True)


if __name__ == "__main__":
    main()
